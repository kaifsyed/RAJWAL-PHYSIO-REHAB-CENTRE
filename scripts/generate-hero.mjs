import fs from "node:fs";
import path from "node:path";

const heroDir = path.join(process.cwd(), "public", "images", "hero");
const outFile = path.join(process.cwd(), "src", "lib", "hero-images.ts");

const exts = new Set([".jpg", ".jpeg", ".png", ".webp", ".avif"]);

let files = [];
if (fs.existsSync(heroDir)) {
  files = fs
    .readdirSync(heroDir)
    .filter((f) => exts.has(path.extname(f).toLowerCase()))
    .sort((a, b) => a.localeCompare(b));
}

const entries = files
  .map((f) => `  "/images/hero/${encodeURIComponent(f)}",`)
  .join("\n");

const content = `// Auto-generated by scripts/generate-hero.mjs. Do not edit manually.
export const HERO_IMAGES: string[] = [
${entries}
];
`;

fs.writeFileSync(outFile, content);
console.log(`Generated ${files.length} hero images.`);