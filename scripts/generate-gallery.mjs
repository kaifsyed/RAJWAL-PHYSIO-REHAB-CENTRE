import fs from "node:fs";
import path from "node:path";

const galleryDir = path.join(process.cwd(), "public", "images", "gallery");
const outFile = path.join(process.cwd(), "src", "lib", "gallery-images.ts");

const exts = new Set([".jpg", ".jpeg", ".png", ".webp", ".avif"]);

let files = [];
if (fs.existsSync(galleryDir)) {
  files = fs
    .readdirSync(galleryDir)
    .filter((f) => exts.has(path.extname(f).toLowerCase()))
    .sort((a, b) => a.localeCompare(b));
}

const entries = files.map((f, i) => `  { src: "/images/gallery/${f}", alt: "Prajwal Physio Rehab Centre clinic gallery image ${i + 1}" },`).join("\n");

const content = `// Auto-generated by scripts/generate-gallery.mjs. Do not edit manually.
export interface GalleryImage {
  src: string;
  alt: string;
}

export const GALLERY_IMAGES: GalleryImage[] = [
${entries}
];
`;

fs.writeFileSync(outFile, content);
console.log(`Generated ${files.length} gallery images.`);